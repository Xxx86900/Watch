def unique_codepoints(text: str) -> list[int]:
    return sorted({ord(character) for character in text})


def render_cjk_glyph(font: ImageFont.FreeTypeFont, codepoint: int) -> bytes:
    image = Image.new("L", (16, 16), 0)
    ImageDraw.Draw(image).text((0, -2), chr(codepoint), font=font, fill=255)
    pixels = image.load()
    packed = bytearray()
    for x in range(16):
        for page in range(2):
            value = 0
            for bit in range(8):
                if pixels[x, page * 8 + bit] >= 128:
                    value |= 1 << bit
            packed.append(value)
    return bytes(packed)


def c_array(name: str, values: bytes, columns: int = 12) -> str:
    lines = [f"static const uint8_t {name}[] =", "{"]
    for start in range(0, len(values), columns):
        chunk = values[start:start + columns]
        lines.append("  " + ", ".join(f"0x{value:02X}U" for value in chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def generate() -> None:
    if len(ASCII_5X7) != 95 * 5:
        raise RuntimeError("ASCII table must contain exactly 95 glyphs")
    if not FONT_PATH.exists():
        raise FileNotFoundError(FONT_PATH)

    codepoints = unique_codepoints(CJK_TEXT)
    font = ImageFont.truetype(str(FONT_PATH), 16)
    font.set_variation_by_axes([400])
    cjk_bitmap = b"".join(render_cjk_glyph(font, cp) for cp in codepoints)

    source = [
        '#include "fonts.h"',
        "",
        "/* Printable ASCII U+0020..U+007E, classic 5x7 pixel font. */",
        c_array("s_font_5x7_bitmap", ASCII_5X7),
        "",
        "/* Noto Sans SC Regular 16x16 glyphs, generated for project UI text. */",
        "static const uint32_t s_font_zh_codepoints[] =",
        "{",
    ]
    for start in range(0, len(codepoints), 8):
        chunk = codepoints[start:start + 8]
        source.append("  " + ", ".join(f"0x{cp:04X}U" for cp in chunk) + ",")
    source.extend([
        "};",
        "",
        c_array("s_font_zh_16x16_bitmap", cjk_bitmap),
        "",
        "const ui_font_t ui_font_5x7 =",
        "{",
        "  .width = 5U,",
        "  .height = 7U,",
        "  .first_character = 0x20U,",
        "  .last_character = 0x7EU,",
        "  .bitmap = s_font_5x7_bitmap",
        "};",
        "",
        "const ui_unicode_font_t ui_font_zh_16x16 =",
        "{",
        "  .width = 16U,",
        "  .height = 16U,",
        f"  .glyph_count = {len(codepoints)}U,",
        "  .codepoints = s_font_zh_codepoints,",
        "  .bitmap = s_font_zh_16x16_bitmap",
        "};",
        "",
    ])
    OUTPUT_PATH.write_text("\n".join(source), encoding="utf-8")
    print(f"Generated {len(codepoints)} Chinese glyphs and 95 ASCII glyphs")


if __name__ == "__main__":
    generate()
